-- -------------------------------------------------------------
-- SECTION 1: RECRUITMENT TABLES
-- These are the core tables used by workforcems-recruitment app
-- WorkforceIQ engineers: these are the tables you are merging with
-- -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS jobs (
    id                  uuid NOT NULL DEFAULT gen_random_uuid(),
    title               text NOT NULL,
    department          text NOT NULL,
    description         text,
    requirements        text,
    type                text DEFAULT 'full-time'::text,
    status              text DEFAULT 'open'::text,
    created_at          timestamp with time zone DEFAULT now(),
    -- Additional fields recommended for WorkforceMS merger:
    salary_range        text,
    location            text,
    closing_date        date,
    employment_type     text,
    PRIMARY KEY (id)
);

COMMENT ON TABLE jobs IS 
'Job postings. Used by WorkforceMS Recruitment module and WorkforceIQ ATS.';

-- -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS applications (
    id                      uuid NOT NULL DEFAULT gen_random_uuid(),
    job_id                  uuid REFERENCES jobs(id) ON DELETE SET NULL,
    candidate_name          text NOT NULL,
    candidate_email         text NOT NULL,
    candidate_phone         text,
    candidate_age           integer,
    candidate_gender        text,
    candidate_school        text,
    cv_text                 text,
    skills                  text[],
    stage                   text DEFAULT 'applied'::text,
    blind_score             numeric,
    ai_summary              text,
    is_blinded              boolean DEFAULT false,
    created_at              timestamp with time zone DEFAULT now(),
    updated_at              timestamp with time zone DEFAULT now(),
    original_cv             text,
    application_reference   text,
    source                  text DEFAULT 'manual'::text,
    years_experience        integer,
    applicant_role          text,
    phone                   text,
    cv_file_url             text,
    PRIMARY KEY (id)
);

COMMENT ON TABLE applications IS 
'Candidate applications. is_blinded controls anonymisation. 
original_cv stores raw CV, cv_text stores anonymised version.
source: manual | careers_portal | import';

COMMENT ON COLUMN applications.is_blinded IS
'When true: candidate_name, candidate_email, candidate_phone, 
candidate_school are hidden from recruiters until manually revealed.';

COMMENT ON COLUMN applications.blind_score IS
'AI-generated score 0-100 based on CV vs role match. 
Generated by Groq llama-3.1-8b-instant via Blind Screener.';

-- -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS feedback (
    id          uuid NOT NULL DEFAULT gen_random_uuid(),
    category    text NOT NULL,
    message     text,
    created_at  timestamp with time zone DEFAULT now(),
    PRIMARY KEY (id)
);

COMMENT ON TABLE feedback IS 
'Anonymous feedback submissions. No reporter_id by design — 
identity cannot be recovered even with direct DB access.';

