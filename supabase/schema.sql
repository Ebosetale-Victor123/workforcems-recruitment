-- -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS onboarding_templates (
    id                  uuid NOT NULL DEFAULT gen_random_uuid(),
    department          text NOT NULL,
    task_name           text NOT NULL,
    task_type           text NOT NULL,
    description         text,
    due_days_after_hire integer DEFAULT 7,
    requires_document   boolean DEFAULT false,
    created_at          timestamp with time zone DEFAULT now(),
    PRIMARY KEY (id)
);

-- -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS payroll (
    id              uuid NOT NULL DEFAULT gen_random_uuid(),
    employee_id     uuid REFERENCES employees(id) ON DELETE CASCADE,
    month           text NOT NULL,
    year            integer NOT NULL,
    basic_salary    numeric,
    allowances      numeric DEFAULT 0,
    deductions      numeric DEFAULT 0,
    tax             numeric DEFAULT 0,
    pension         numeric DEFAULT 0,
    net_pay         numeric,
    status          text DEFAULT 'pending'::text,
    created_at      timestamp with time zone DEFAULT now(),
    paid_at         timestamp with time zone,
    transaction_id  uuid,
    PRIMARY KEY (id)
);

-- -------------------------------------------------------------

CREATE TABLE IF NOT EXISTS transactions (
    id                      uuid NOT NULL DEFAULT gen_random_uuid(),
    employee_id             uuid REFERENCES employees(id) ON DELETE SET NULL,
    payroll_id              uuid REFERENCES payroll(id) ON DELETE SET NULL,
    amount                  numeric NOT NULL,
    bank_name               text,
    account_number          text,
    account_name            text,
    paystack_reference      text,
    paystack_recipient_code text,
    status                  text DEFAULT 'pending'::text,
    failure_reason          text,
    paid_at                 timestamp with time zone,
    created_at              timestamp with time zone DEFAULT now(),
    PRIMARY KEY (id)
);

COMMENT ON TABLE transactions IS
'Paystack payment records. Status: pending | success | failed. 
paystack_reference links to live Paystack dashboard.';

-- -------------------------------------------------------------

